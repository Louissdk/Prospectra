import test from 'node:test';
import assert from 'node:assert/strict';
import { createXlsx } from '../workbook.js';
import { parseXlsxRows } from '../spreadsheet-import.js';

test('imports an XLSX workbook generated by Prospectra', async () => {
  const workbook = createXlsx([
    { name:'Clínica Exemplo', category:'Odontologia', phone:'(11) 99999-0000', emails:['contato@clinica.example'], city:'Guarulhos' }
  ]);
  const rows = await parseXlsxRows({ arrayBuffer: () => workbook.arrayBuffer() });
  assert.equal(rows[0][0],'Nome do lead');
  assert.equal(rows[1][0],'Clínica Exemplo');
  assert.equal(rows[1][1],'Odontologia');
  assert.equal(rows[1][2],'(11) 99999-0000');
});

import { deflateRawSync } from 'node:zlib';

function crc32(bytes) {
  let crc=0xFFFFFFFF;
  for (const byte of bytes) {
    crc^=byte;
    for(let bit=0;bit<8;bit++) crc=(crc&1)?(0xEDB88320^(crc>>>1)):(crc>>>1);
  }
  return (crc^0xFFFFFFFF)>>>0;
}
function buildDeflatedZip(files) {
  const locals=[],centrals=[];
  let offset=0;
  for(const [name,content] of files) {
    const nameBytes=Buffer.from(name,'utf8');
    const raw=Buffer.from(content,'utf8');
    const compressed=deflateRawSync(raw);
    const crc=crc32(raw);
    const local=Buffer.alloc(30+nameBytes.length);
    local.writeUInt32LE(0x04034b50,0);
    local.writeUInt16LE(20,4);
    local.writeUInt16LE(0x0800,6);
    local.writeUInt16LE(8,8);
    local.writeUInt32LE(crc,14);
    local.writeUInt32LE(compressed.length,18);
    local.writeUInt32LE(raw.length,22);
    local.writeUInt16LE(nameBytes.length,26);
    nameBytes.copy(local,30);
    locals.push(local,compressed);

    const central=Buffer.alloc(46+nameBytes.length);
    central.writeUInt32LE(0x02014b50,0);
    central.writeUInt16LE(20,4);
    central.writeUInt16LE(20,6);
    central.writeUInt16LE(0x0800,8);
    central.writeUInt16LE(8,10);
    central.writeUInt32LE(crc,16);
    central.writeUInt32LE(compressed.length,20);
    central.writeUInt32LE(raw.length,24);
    central.writeUInt16LE(nameBytes.length,28);
    central.writeUInt32LE(offset,42);
    nameBytes.copy(central,46);
    centrals.push(central);
    offset+=local.length+compressed.length;
  }
  const centralSize=centrals.reduce((sum,item)=>sum+item.length,0);
  const end=Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50,0);
  end.writeUInt16LE(files.length,8);
  end.writeUInt16LE(files.length,10);
  end.writeUInt32LE(centralSize,12);
  end.writeUInt32LE(offset,16);
  return new Blob([...locals,...centrals,end]);
}

test('imports a deflated XLSX using shared strings and workbook relationships', async () => {
  const workbook='<?xml version="1.0"?><workbook xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Leads" sheetId="1" r:id="rId1"/></sheets></workbook>';
  const relationships='<?xml version="1.0"?><Relationships><Relationship Id="rId1" Target="worksheets/sheet1.xml"/></Relationships>';
  const sharedStrings='<?xml version="1.0"?><sst><si><t>Nome do lead</t></si><si><t>Empresa</t></si><si><t>Telefone</t></si><si><t>(11) 99999-0000</t></si></sst>';
  const sheet='<?xml version="1.0"?><worksheet><sheetData><row r="1"><c r="A1" t="s"><v>0</v></c><c r="B1" t="s"><v>2</v></c></row><row r="2"><c r="A2" t="s"><v>1</v></c><c r="B2" t="s"><v>3</v></c></row></sheetData></worksheet>';
  const blob=buildDeflatedZip([
    ['xl/workbook.xml',workbook],
    ['xl/_rels/workbook.xml.rels',relationships],
    ['xl/sharedStrings.xml',sharedStrings],
    ['xl/worksheets/sheet1.xml',sheet]
  ]);
  const rows=await parseXlsxRows({arrayBuffer:()=>blob.arrayBuffer()});
  assert.deepEqual(rows,[['Nome do lead','Telefone'],['Empresa','(11) 99999-0000']]);
});
